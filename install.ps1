# codex-no-stop installer
#
# Reads your existing ~/.codex/config.toml, learns which custom provider you use
# and where its base_url points, then prepares a local retry proxy.
# config.toml is NOT modified; the override is passed to Codex at run time.

param([switch]$NoGlobal)

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path

function Stop-WithError([string]$msg) {
  Write-Host ""
  Write-Host "ERROR: $msg" -ForegroundColor Red
  Write-Host ""
  Read-Host "Press Enter to exit" | Out-Null
  exit 1
}

Write-Host "=== codex-no-stop installer ===" -ForegroundColor Cyan
Write-Host ""

# ---- 1. prerequisites -------------------------------------------------------
if (-not (Get-Command node -ErrorAction SilentlyContinue)) {
  Stop-WithError "Node.js not found in PATH. Install it from https://nodejs.org/ then run install.cmd again."
}
if (-not (Get-Command codex -ErrorAction SilentlyContinue)) {
  Stop-WithError "Codex CLI not found in PATH. Install it first: npm install -g @openai/codex"
}

# ---- 2. read the user's provider from config.toml ---------------------------
$configPath = Join-Path $env:USERPROFILE ".codex\config.toml"
if (-not (Test-Path -LiteralPath $configPath)) {
  Stop-WithError "config.toml not found at: $configPath"
}
$text = Get-Content -LiteralPath $configPath -Raw -Encoding UTF8

$m = [regex]::Match($text, '(?m)^[ \t]*model_provider[ \t]*=[ \t]*"([^"]+)"')
if (-not $m.Success) {
  Stop-WithError "No model_provider setting found in config.toml."
}
$provider = $m.Groups[1].Value

$sectionRe = '(?ms)^[ \t]*\[model_providers\.' + [regex]::Escape($provider) + '\][ \t]*\r?\n(.*?)(?=^[ \t]*\[|\z)'
$section = [regex]::Match($text, $sectionRe)
if (-not $section.Success) {
  Stop-WithError ("config.toml has no [model_providers.{0}] section.`nOnly custom providers (the ones that define base_url in config.toml) are supported." -f $provider)
}

$bm = [regex]::Match($section.Groups[1].Value, '(?m)^[ \t]*base_url[ \t]*=[ \t]*"([^"]+)"')
if (-not $bm.Success) {
  Stop-WithError ("No base_url found in [model_providers.{0}]." -f $provider)
}

$baseUrl = $bm.Groups[1].Value.Trim()
try { $uri = [Uri]$baseUrl } catch { Stop-WithError "base_url is not a valid URL: $baseUrl" }
if (-not $uri.IsAbsoluteUri) { Stop-WithError "base_url is not an absolute URL: $baseUrl" }

$origin   = $uri.GetLeftPart([UriPartial]::Authority)   # e.g. https://relay.example.com
$basePath = $uri.AbsolutePath.TrimEnd('/')              # e.g. /v1

$port = $env:CODEX_RETRY_PORT
if (-not $port) { $port = '8788' }

Write-Host ("Provider   : {0}" -f $provider)
Write-Host ("Upstream   : {0}" -f $origin)
Write-Host ("Base path  : {0}" -f $basePath)
Write-Host ("Local port : {0}" -f $port)
Write-Host ""

# ---- 3. write settings used by the wrapper scripts --------------------------
$settings = @(
  "rem generated by install.ps1 - do not edit by hand",
  "set `"CODEX_PROVIDER=$provider`"",
  "set `"CODEX_UPSTREAM=$origin`"",
  "set `"CODEX_BASE_PATH=$basePath`"",
  "set `"CODEX_RETRY_PORT=$port`""
) -join "`r`n"
Set-Content -LiteralPath (Join-Path $here 'settings.cmd') -Value ($settings + "`r`n") -Encoding Default

$vbs = @"
' generated by install.ps1 - starts the retry proxy with no console window
Set sh = CreateObject("WScript.Shell")
sh.Run """$here\start-proxy.cmd""", 0, False
"@
Set-Content -LiteralPath (Join-Path $here 'start-proxy-hidden.vbs') -Value ($vbs + "`r`n") -Encoding Default

# ---- 4. start the proxy once and verify it answers --------------------------
Start-Process -FilePath 'wscript.exe' -ArgumentList ('"' + (Join-Path $here 'start-proxy-hidden.vbs') + '"') -WindowStyle Hidden
Start-Sleep -Seconds 3

$proxyOk = $false
try {
  $h = Invoke-RestMethod -Uri ("http://127.0.0.1:{0}/__health" -f $port) -TimeoutSec 3
  if ($h.ok) { $proxyOk = $true }
} catch { }

if ($proxyOk) {
  Write-Host "Proxy is running." -ForegroundColor Green
} else {
  Write-Host "WARNING: the proxy did not answer on port $port." -ForegroundColor Yellow
  Write-Host "Run start-proxy.cmd in this folder to see the error message." -ForegroundColor Yellow
}

# ---- 5. make `codex-retry` available in any directory -----------------------
if (-not $NoGlobal) {
  $installed = $false

  $npmPrefix = $null
  try { $npmPrefix = (& npm prefix -g | Select-Object -Last 1) } catch { $npmPrefix = $null }
  if ($npmPrefix) { $npmPrefix = $npmPrefix.Trim() }

  if ($npmPrefix -and $npmPrefix -match '^[A-Za-z]:\\' -and (Test-Path -LiteralPath $npmPrefix)) {
    $launcher = "@echo off`r`nrem Global launcher for codex-no-stop (real logic lives in $here)`r`ncall `"$here\codex-retry.cmd`" %*`r`nexit /b %errorlevel%`r`n"
    Set-Content -LiteralPath (Join-Path $npmPrefix 'codex-retry.cmd') -Value $launcher -Encoding Default
    Write-Host ("Global command installed: {0}" -f (Join-Path $npmPrefix 'codex-retry.cmd'))
    $installed = $true
  }

  if (-not $installed) {
    $userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
    if ($userPath -and ($userPath.Split(';') -contains $here)) {
      Write-Host "Already on your user PATH: $here"
    } else {
      $newPath = if ([string]::IsNullOrEmpty($userPath)) { $here } else { $userPath.TrimEnd(';') + ';' + $here }
      [Environment]::SetEnvironmentVariable('Path', $newPath, 'User')
      Write-Host "Added to your user PATH: $here"
      Write-Host "Open a NEW terminal window for it to take effect."
    }
    $installed = $true
  }
}

Write-Host ""
Write-Host "Done. Use  codex-retry  instead of  codex." -ForegroundColor Green
Write-Host "Example:  codex-retry exec `"fix the bug`""
Write-Host "          codex-retry              (interactive)"
Write-Host ""
Read-Host "Press Enter to exit" | Out-Null
